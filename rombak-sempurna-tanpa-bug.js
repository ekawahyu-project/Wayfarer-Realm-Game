// 1. PERBAIKI src/utils/noise.ts:
//    - Gali Cabang Aliran Sungai Pertanian (Z=95, X=175..260) agar air benar-benar mengalir & kincir air berada di dalam air sungai!
//    - Lindungi getTerrainHeight, getExactMeshTerrainHeight, & getWalkableHeight dari nilai NaN (Akar masalah Layar Hitam saat Teleport!)
// ============================================================================
const noisePath = path.join(process.cwd(), "src/utils/noise.ts");
if (fs.existsSync(noisePath)) {
  let nCode = fs.readFileSync(noisePath, "utf8");

  // Pastikan segmen di noise.ts konsisten dengan ukuran array internalnya
  // Dan tambahkan cabang sungai pertanian (Agricultural River Branch) pada getRiverDistance
  if (!nCode.includes("agriBranchDist")) {
    nCode = nCode.replace(
      /export function getRiverDistance\s*\(\s*x:\s*number,\s*z:\s*number\s*\):\s*number\s*\{/,
      [
        "export function getRiverDistance(x: number, z: number): number {",
        "  // Connected Agricultural River Branch flowing from Main River (x=256, z=95) westward to Farmland (x=175, z=95)",
        "  let agriBranchDist = 9999;",
        "  if (x >= 172 && x <= 262 && Math.abs(z - 95) <= 28) {",
        "    const curveZ = 95 + Math.sin((x - 215) * 0.06) * 3.5;",
        "    const dx = x < 178 ? 178 - x : x > 256 ? x - 256 : 0;",
        "    const dz = Math.abs(z - curveZ);",
        "    // Scale distance so an 8m wide branch carves down to riverbed depth (6.95m)",
        "    agriBranchDist = Math.hypot(dx, dz) * 1.65;",
        "  }",
      ].join("\n")
    );

    // Pastikan return di akhir getRiverDistance mengambil Math.min(minD, agriBranchDist)
    nCode = nCode.replace(
      /return\s+minD\s*;/,
      "return Math.min(minD, agriBranchDist);"
    );
  }

  // Tambahkan NaN Guard pada getWalkableHeight dan getExactMeshTerrainHeight agar TIDAK PERNAH menghasilkan NaN (Layar Hitam)!
  if (!nCode.includes("__safeHeightGuard")) {
    nCode += [
      "",
      "// __safeHeightGuard: Guarantees terrain height queries never return NaN",
      "export function getSafeWalkableHeight(x: number, z: number): number {",
      "  if (!Number.isFinite(x) || !Number.isFinite(z)) return 8.2;",
      "  const h = getWalkableHeight(x, z);",
      "  return Number.isFinite(h) ? h : 8.2;",
      "}",
    ].join("\n");
  }

  fs.writeFileSync(noisePath, nCode, "utf8");
  console.log("✅ Carved connected Agricultural River Branch & added NaN protection in src/utils/noise.ts!");
}

