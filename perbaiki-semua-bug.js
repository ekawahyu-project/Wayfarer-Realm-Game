const fs = require("fs");
const path = require("path");

function writeLines(filePath, lines) {
  const fullPath = path.join(process.cwd(), filePath);
  fs.mkdirSync(path.dirname(fullPath), { recursive: true });
  fs.writeFileSync(fullPath, lines.join("\n") + "\n", "utf8");
  console.log("✅ Updated:", filePath);
}

// 1. PERBAIKI src/utils/noise.ts (Hapus duplikat fungsi noise2D di bawah & tambahkan export pada const noise2D di baris 12)
const noisePath = path.join(process.cwd(), "src/utils/noise.ts");
let detectedSize = 1400;
let detectedSegments = 220;

if (fs.existsSync(noisePath)) {
  let nCode = fs.readFileSync(noisePath, "utf8");

  // Hapus blok fallback noise2D yang menyebabkan duplikat deklarasi
  nCode = nCode.replace(/\n*\/\/ Fallback export for noise2D[\s\S]*$/, "");

  // Pastikan setiap deklarasi function/const noise2D tambahan dihapus jika ada lebih dari satu
  const matches = [...nCode.matchAll(/(?:export\s+)?(?:const|function)\s+noise2D\b/g)];
  if (matches.length > 1) {
    const lastMatch = matches[matches.length - 1];
    nCode = nCode.slice(0, lastMatch.index).trimEnd() + "\n";
  }

  // Ubah `const noise2D =` menjadi `export const noise2D =`
  nCode = nCode.replace(/^\s*const\s+noise2D\s*=/m, "export const noise2D =");

  // Deteksi ukuran grid fisika asli dari noise.ts agar Terrain.tsx 100% sinkron
  const sizeMatch = nCode.match(/(?:WORLD_SIZE|TERRAIN_SIZE|size)\s*=\s*(\d+)/);
  const segMatch = nCode.match(/(?:TERRAIN_SEGMENTS|SEGMENTS|segments)\s*=\s*(\d+)/);
  if (sizeMatch) detectedSize = parseInt(sizeMatch[1], 10);
  if (segMatch) detectedSegments = parseInt(segMatch[1], 10);

  fs.writeFileSync(noisePath, nCode.trimEnd() + "\n", "utf8");
  console.log(`✅ Fixed duplicate noise2D in src/utils/noise.ts! (Grid: ${detectedSize}m, ${detectedSegments} segments)`);
}

