  '',
  'const SHADOW_FRUSTUM = 95;',
  'const SHADOW_MAP_SIZE = 2048;',
  '',
  'export default function TimeOfDay() {',
  '  const { gl } = useThree();',
  '  const sunLightRef = useRef<THREE.DirectionalLight>(null);',
